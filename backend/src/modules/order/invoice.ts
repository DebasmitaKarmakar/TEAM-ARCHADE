import { gstFor } from '../../config/tax';
import { fmtINR } from '../../lib/money';
import { prisma } from '../../lib/prisma';
import { AppError } from '../../utils/AppError';

const esc = (s: string) => s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);

/** Printable tax invoice (open in a tab → Ctrl/Cmd+P → Save as PDF). */
export async function renderInvoice(userId: string, orderNumber: string) {
  const o = await prisma.order.findUnique({ where: { orderNumber }, include: { items: true, user: true } });
  if (!o || o.userId !== userId) throw new AppError(404, 'Order not found');
  if (o.status === 'PENDING_PAYMENT') throw new AppError(409, 'Invoice is available after payment');
  const depts = new Map((await prisma.department.findMany()).map((d) => [d.id, d]));
  const a = o.addressSnapshot as Record<string, string>;
  const rows = o.items.filter((i) => i.status !== 'CANCELLED').map((i) => {
    const d = depts.get(i.departmentId);
    const rate = gstFor(d?.slug ?? '');
    const tax = Math.round((i.lineTotal * rate) / (100 + rate));
    return `<tr><td>${esc(i.nameSnapshot)}<br><small>${esc(Object.values(i.optionsSnapshot as Record<string, string>).join(' · '))}</small></td>
      <td>${esc(d?.name ?? '')}</td><td>${i.qty}</td><td>${fmtINR(i.unitPrice)}</td><td>${fmtINR(i.lineDiscount)}</td>
      <td>${rate}%</td><td>${fmtINR(tax)}</td><td>${fmtINR(i.lineTotal)}</td></tr>`;
  }).join('');
  return `<!doctype html><html><head><meta charset="utf-8"><title>Invoice ${o.orderNumber}</title>
  <style>body{font:14px Inter,Arial,sans-serif;color:#16131C;margin:40px}h1{font:900 32px Georgia,serif;margin:0}
  table{width:100%;border-collapse:collapse;margin-top:20px}td,th{border-bottom:1px solid #EDE7DF;padding:8px;text-align:left;vertical-align:top}
  th{font-size:11px;letter-spacing:.15em;text-transform:uppercase;color:#6B6475}.tot td{border:none}small{color:#6B6475}</style></head>
  <body><h1>BLOWMAGGY</h1><div style="color:#6B6475">Tax Invoice · ${o.orderNumber} · ${o.createdAt.toLocaleDateString('en-IN', { timeZone: 'Asia/Kolkata' })}</div>
  <p><b>Bill to:</b> ${esc(a.name ?? o.user.name)}, ${esc(a.line1 ?? '')}${a.line2 ? ', ' + esc(a.line2) : ''}, ${esc(a.city ?? '')}, ${esc(a.state ?? '')} ${esc(a.pincode ?? '')}</p>
  <table><tr><th>Item</th><th>Dept</th><th>Qty</th><th>Price</th><th>Discount</th><th>GST</th><th>GST amt</th><th>Total</th></tr>${rows}</table>
  <table class="tot" style="width:320px;margin-left:auto">
  <tr><td>Subtotal</td><td style="text-align:right">${fmtINR(o.subtotal)}</td></tr>
  <tr><td>Discounts</td><td style="text-align:right">−${fmtINR(o.discountTotal)}</td></tr>
  <tr><td>Delivery</td><td style="text-align:right">${fmtINR(o.deliveryFee)}</td></tr>
  <tr><td><b>Total (incl. GST ${fmtINR(o.tax)})</b></td><td style="text-align:right"><b>${fmtINR(o.total)}</b></td></tr></table>
  <p style="margin-top:40px;color:#6B6475;font-size:12px">Demo invoice generated by Blowmaggy · Vibe Coding Competition 2026</p></body></html>`;
}
